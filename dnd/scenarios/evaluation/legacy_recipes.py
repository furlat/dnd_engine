LEGACY_RECIPES_BY_ID = {recipe.arena_id: recipe for recipe in LEGACY_RECIPES}


def get_legacy_recipe(arena_id: str) -> LegacyScenarioRecipe:
    """Return one legacy composition recipe by arena identifier."""
    try:
        return LEGACY_RECIPES_BY_ID[arena_id]
    except KeyError as exc:
        raise ValueError(f"Unknown legacy scenario recipe: {arena_id}") from exc
