from __future__ import annotations

from dnd.scenarios.evaluation.models import ActorPresentation, LegacyScenarioRecipe, NotablePosition


def _recipe(
    arena_id: str,
    hero_configuration_id: str,
    monster_configuration_id: str,
    battlefield_id: str,
    encounter_name: str,
    actor_names: tuple[str, ...],
    notable_positions: dict[str, tuple[int, int]],
) -> LegacyScenarioRecipe:
    """Create one role-addressed legacy composition recipe."""
    roles = ("hero", *(f"monster_{index}" for index in range(1, len(actor_names))))
    return LegacyScenarioRecipe(
        arena_id=arena_id,
        hero_configuration_id=hero_configuration_id,
        monster_configuration_id=monster_configuration_id,
        battlefield_id=battlefield_id,
        deployment_id=f"legacy.{arena_id}",
        encounter_name=encounter_name,
        actor_presentations=tuple(
            ActorPresentation(role=role, name=name)
            for role, name in zip(roles, actor_names)
        ),
        notable_positions=tuple(
            NotablePosition(label=label, position=position)
            for label, position in notable_positions.items()
        ),
    )


